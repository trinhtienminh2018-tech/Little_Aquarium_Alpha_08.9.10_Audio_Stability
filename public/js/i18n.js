export const currentLanguage = () => language;
const dynamic = [
  [/^(.+?) · (Quang đãng|Có gió|Mưa giông) · (Ban ngày|Hoàng hôn|Buổi tối)$/, (m) => `${m[1]} · ${translate(m[2])} · ${translate(m[3])}`],
  [/^(Quang đãng|Có gió|Mưa giông) · (Ban ngày|Hoàng hôn|Buổi tối) · (Cửa mở|Cửa đóng|Thế giới đang sống)$/, (m) => `${translate(m[1])} · ${translate(m[2])} · ${translate(m[3])}`],
  [/^(\d\d?:\d\d) · (Ban ngày|Hoàng hôn|Buổi tối) · Đang đồng bộ$/, (m) => `${m[1]} · ${translate(m[2])} · Syncing`],
  [/^Tăng số lượng (.+)$/, m=>`Increase ${translate(m[1])}`],
  [/^Giảm số lượng (.+)$/, m=>`Decrease ${translate(m[1])}`],
  [/^Chất lượng chuyển động: (.+)$/, m=>`Animation quality: ${translate(m[1])}`],
];
export function translate(source) {
  if(language !== 'en')return source;
  if(EN[source])return EN[source];
  for(const [re, fn] of dynamic){const m=source.match(re);if(m)return fn(m);}
  return source;
}
// A translation owns its original Vietnamese source. Game updates can replace that
// source at any time; translated text itself must not become the new source.
function translateNode(node){
  if(node.nodeType === 3){
    if(!node.nodeValue.trim())return;
    let record=original.get(node);
    if(record === undefined || (node.nodeValue !== record.source && node.nodeValue !== record.rendered)){
      record={source:node.nodeValue,rendered:node.nodeValue};
    }
    const next=renderText(record.source);
    record.rendered=next;
    original.set(node,record);
    if(node.nodeValue !== next)node.nodeValue=next;
    return;
  }
  if(node.nodeType!==1 || ['SCRIPT','STYLE','CANVAS','NOSCRIPT'].includes(node.tagName))return;
  for(const attr of ['title','aria-label','placeholder','data-hint','alt']){
    if(!node.hasAttribute(attr))continue;
    const value=node.getAttribute(attr);
    const key='i18nVi'+attr.replace(/[^a-zA-Z]/g,'');
    let source=node.dataset[key];
    const renderedKey=key+'Rendered';
    if(source === undefined || (value !== source && value !== node.dataset[renderedKey]))source=value;
    node.dataset[key]=source;
    const next=translate(source);
    node.dataset[renderedKey]=next;
    if(value!==next)node.setAttribute(attr,next);
  }
  for(const child of node.childNodes)translateNode(child);
}
function renderText(raw){
  const prefix=raw.match(/^\s*/)[0], suffix=raw.match(/\s*$/)[0];
  return prefix+translate(raw.trim())+suffix;
}
let running=false;
export function refreshLanguage(){
  if(running)return;
  running=true;
  try{
    document.documentElement.lang=language;
    translateNode(document.body);
    const choose=document.getElementById('language-choice');
    if(choose)choose.value=language;
  }finally{running=false;}
}
export function setLanguage(code){
  language=code==='vi'?'vi':'en';
  try{localStorage.setItem('aquarium2.language',language);}catch{}
  refreshLanguage();
}
export function startTranslations(){
  refreshLanguage();
  // Observe the complete interface, including dynamically created species rows.
  // Attribute changes made only by styling or animations are intentionally ignored.
  const observer=new MutationObserver(changes=>{
    if(running)return;
    if(changes.some(m=>m.type==='characterData'||m.type==='childList'||
      (m.type==='attributes'&&['title','aria-label','placeholder','data-hint','alt'].includes(m.attributeName)))){
      refreshLanguage();
    }
  });
  observer.observe(document.body,{subtree:true,childList:true,characterData:true,
    attributes:true,attributeFilter:['title','aria-label','placeholder','data-hint','alt']});
}
